using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using Newtonsoft.Json;
using Newtonsoft.Json.Linq;

namespace Neko.RimWorld;

/// <summary>Budget facts and their growing explanatory metadata before committing delivery.</summary>
internal sealed partial class ObjectReadEngine
{
    private JObject DeliveryEnvelope(JObject body,ReadTraversal work,Run run,int start,int steps,bool complete,string token,bool probe=false) {
        var result=(JObject)body.DeepClone();
        result["sample"]=work.Projection["sample"]!.DeepClone();result["sample"]!["finished_tick"]=probe?long.MinValue:run.Tick();
        result["status"]=probe || work.HadIssues || Incomplete(body)?"partial":"ok";
        result["delivery"]=new JObject { ["projection_id"]=work.Id,["complete"]=start==0 && complete,["end_of_projection"]=complete,
            ["cursor_scope"]="selection",
            ["leaf_start"]=probe?int.MinValue:start,["leaf_end"]=probe?int.MinValue:work.LeafOffset,
            ["total_leaves"]=probe?new JValue(int.MinValue):complete?new JValue(work.LeafOffset):JValue.CreateNull(),
            ["source_page"]=probe?MaximumSourcePage(token):work.Projection["page"]?.DeepClone(),
            ["meaning"]="Lossless selection traversal; facts and explanatory metadata share the delivery budget." };
        result["execution"]=new JObject { ["identity_candidates"]=probe?int.MinValue:run.CandidateReads,["selected_field_accesses"]=probe?int.MinValue:run.GetterReads,
            ["native_getter_reads"]=probe?int.MinValue:run.Context.NativeGetterReads,["dispatch_steps"]=probe?int.MinValue:Math.Min(steps,TraversalSteps),
            ["selection_traversal_complete"]=complete,["source_cost"]="Necessary identity capture and per-frame membership verification are source-population work; dispatch quantum is not a CPU bound." };
        if(probe || !complete) {
            result["page"]=probe?MaximumSourcePage(token):new JObject { ["kind"]="selection_window",["has_more"]=true,["cursor"]=token };
            if(result["coverage"] is JObject coverage)coverage["display_complete"]=false;
        }
        return result;
    }

    // Probe envelope size from the tracked body size: only the top-level members the
    // envelope replaces are re-encoded. Compact JSON size is 2 + members + separators.
    private static readonly string[] EnvelopeMembers={"sample","status","delivery","execution","page","coverage"};
    private int ProbeSize(JObject body,int bodySize,ReadTraversal work,Run run,int start,int steps,string token) {
        var shell=new JObject();
        foreach(var name in EnvelopeMembers)if(body.TryGetValue(name,out var value))shell[name]=value!.DeepClone();
        // A probe envelope only varies with these members, the projection sample and the token.
        var key=shell.ToString(Formatting.None)+"\u0000"+work.Projection["sample"]!.ToString(Formatting.None)+"\u0000"+token;
        if(key!=work.ProbeKey) {
            var wrapped=DeliveryEnvelope(shell,work,run,start,steps,false,token,true);
            int Members(JObject value)=>DeliverySize(value)-2-Math.Max(value.Count-1,0);
            work.ProbeKey=key;work.ProbeDelta=Members(wrapped)-Members(shell)+wrapped.Count-shell.Count;
        }
        return bodySize+work.ProbeDelta;
    }

    // Exact structural maximum for fields generated by SourceMetadata. This
    // is measured JSON, not an allowance for unbounded metadata appended later.
    private static JObject MaximumSourcePage(string token)=>new() { ["kind"]="selection_window",["offset"]=int.MinValue,
        ["visited_through"]=int.MinValue,["returned_count"]=int.MinValue,["window_complete"]=false,["has_more"]=false,["cursor"]=token };
    private static int DeliverySize(JObject value)=>Encoding.UTF8.GetByteCount(value.ToString(Formatting.None));
    private static JObject PublishedScope(JObject scope) {
        var result=(JObject)scope.DeepClone();
        if(result["cell_x"] is JArray xs && result["cell_z"] is JArray zs) {
            result.Remove("cell_x");result.Remove("cell_z");
            result["cell_grid"]=new JObject { ["x_count"]=xs.Count,["z_count"]=zs.Count,
                ["meaning"]="Coordinates are the bound target.where x/z selection, preserved in the original request." };
        }
        return result;
    }

    private void QueueExplanations(ReadTraversal work,Run run) {
        while(run.ExplainedIssueCount<run.Issues.Count)QueueIssue(work,run,run.Issues[run.ExplainedIssueCount++],null);
        foreach(var source in work.ExplanationSources.Values)
            while(source.ExplainedIssueCount<source.Source.SourceIssues.Count)
                QueueIssue(work,run,source.Source.SourceIssues[source.ExplainedIssueCount++],source);
        foreach(var rule in run.SemanticRules.Properties()) {
            if(!work.SeenRules.Add(rule.Name))continue;
            var branch=ExplanationBody(run);
            branch["semantic_rules"]=new JObject { [rule.Name]=rule.Value.DeepClone() };
            WindowExplanatoryText(branch,work,run);work.PendingDelivery.Enqueue(branch);
        }
    }

    private void QueueIssue(ReadTraversal work,Run run,QueryIssue issue,ExplanationSource? source) {
        var data=JObject.FromObject(issue);var identity=GameQueryEngine.Hash(data.ToString(Formatting.None));
        var location=source==null?"root":source.Source.Id;
        if(!work.SeenIssues.Add(location+":"+identity))return;
        work.HadIssues=true;data["issue_id"]=identity;
        JObject branch;
        if(source==null) { branch=ExplanationBody(run);branch["issues"]=new JArray(data); }
        else {
            var node=MetadataOnly(source.Node);node["issues"]=new JArray(data);
            branch=ObjectReadPages.Branch(work.Projection,source.Path,node);
        }
        branch["status"]="partial";WindowExplanatoryText(branch,work,run);work.PendingDelivery.Enqueue(branch);
    }

    private static JObject ExplanationBody(Run run)=>new() { ["version"]=ObjectReadContract.Version,
        ["scope"]=PublishedScope(run.Root.Locator.Scope),["rows"]=new JArray(),["issues"]=new JArray(),
        ["sample"]=new JObject { ["load_epoch"]=run.Session.LoadEpoch,["started_tick"]=run.Started,["finished_tick"]=run.Tick(),["atomic"]=false } };

    private void WindowExplanatoryText(JObject branch,ReadTraversal work,Run run) {
        var texts=branch.Descendants().OfType<JProperty>().Where(p=>p.Name is "message" or "meaning")
            .Select(p=>p.Value).OfType<JValue>().Where(v=>v.Value is string content && content.Length>2048).ToArray();
        foreach(var text in texts) {
            var path=TokenPath(text,branch);var original=(string)text.Value!;
            var template=(JObject)branch.DeepClone();JToken slot=template;
            foreach(var part in path)slot=part is int index?slot[index]!:slot[(string)part]!;
            slot.Replace(new JObject { ["__text_window_slot__"]=true });
            var property=(JProperty)text.Parent!;
            text.Replace(ScheduleValue(new JValue(original),template,(JObject)property.Parent!,property.Name,work,run));
        }
    }
    private JObject ScheduleValue(JToken value,JObject template,JObject destination,string name,ReadTraversal work,Run run) {
        var original=value.DeepClone();
        // Only the one selected value is encoded, never its observation envelope.
        // This preserves arbitrary nested JSON types while keeping a single cursor.
        if(value is JObject || value is JArray array && array.Any(NeedsValueWindow)) {
            var slot=template.Descendants().OfType<JObject>().Single(o=>(bool?)o["__text_window_slot__"]==true);
            slot["encoding"]="json";slot["json_type"]=value is JArray?"array":"object";
            value=new JValue(value.ToString(Formatting.None));
        }
        var pending=new TextDelivery { Value=value.DeepClone(),Original=original,Template=template,Destination=destination,Name=name };
        var first=ValueWindow(value,0,template,run,pending.Id,work);pending.Offset=(int)(first["returned_chars"]??first["returned_items"])!;
        if((bool)first["has_more"]!)work.TextValues.Enqueue(pending);
        return first;
    }
    private static bool NeedsValueWindow(JToken value)=>value.Type==JTokenType.String && ((string)value!).Length>2048 ||
        value is JArray array && (array.Count>20 || array.Any(NeedsValueWindow)) ||
        value is JObject obj && (DeliverySize(obj)>60000 || obj.Properties().Any(p=>NeedsValueWindow(p.Value)));
    private JObject ValueWindow(JToken value,int offset,JObject template,Run run,string identity,ReadTraversal work) {
        int Size(JObject window) {
            var body=new JObject { ["rows"]=new JArray(),["issues"]=new JArray(),["semantic_rules"]=new JObject() };
            ObjectReadPages.Merge(body,TextBranch(template,window));
            return DeliverySize(DeliveryEnvelope(body,work,run,int.MinValue,int.MinValue,false,new string('0',32),true));
        }
        if(value.Type==JTokenType.String)return TextWindowWithinBudget((string)value!,offset,template,identity,Size);
        var items=(JArray)value;var count=Math.Min(1024,items.Count-offset);
        JObject Window(int width)=>new() { ["value_snapshot_id"]=identity,["items"]=new JArray(items.Skip(offset).Take(width).Select(v=>v.DeepClone())),
            ["offset"]=offset,["returned_items"]=width,["total_items"]=items.Count,["unit"]="items",
            ["complete"]=offset==0 && width==items.Count,["end_of_value"]=offset+width==items.Count,["has_more"]=offset+width<items.Count };
        while(count>0 && Size(Window(count))>DeliveryBytes)count/=2;
        if(count==0)throw ReadContext.Error("projection_block_too_large","One array item and its required identity exceed the window.");
        return Window(count);
    }
    private static JObject TextBranch(JObject template,JObject window) {
        var result=(JObject)template.DeepClone();
        result.Descendants().OfType<JObject>().Single(o=>(bool?)o["__text_window_slot__"]==true).Replace(window.DeepClone());
        return result;
    }
}
